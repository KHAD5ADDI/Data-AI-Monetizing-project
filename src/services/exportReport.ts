import type { AnalyzedPatent, SearchRunResult } from '../types';

export function buildMarkdownReport(result: SearchRunResult, selectedPatent?: AnalyzedPatent): string {
  const patents = selectedPatent ? [selectedPatent] : result.patents;
  const date = new Date().toISOString().slice(0, 10);
  const lines: string[] = [
    `# Verbatim Prior-Art Claim Chart Report`,
    '',
    `- **Generated:** ${date}`,
    `- **Analysis mode:** ${result.mode === 'live' ? `Live AI (${result.usage?.model ?? 'Claude'}) + Verbatim Guardrail` : 'Local BM25F Deterministic + Verbatim Guardrail'}`,
    `- **Domain score:** ${(result.domain * 100).toFixed(1)}% (threshold ${(result.domainSignals.threshold * 100).toFixed(0)}%)`,
    `- **Verified quotes:** ${result.totals.verifiedQuotes} verified, ${result.totals.rejectedQuotes} rejected`,
    '',
    '## Invention Description',
    '',
    result.invention,
    '',
  ];

  for (const [idx, p] of patents.entries()) {
    lines.push(`## ${selectedPatent ? '' : `#${idx + 1} · `}${p.pub} — ${p.title}`);
    lines.push('');
    lines.push(
      `- **CPC:** \`${p.cpc || p.cpc_group || 'G06'}\` · **Published:** ${p.date || 'N/A'} · **BM25F Score:** ${p.bm25.toFixed(2)} · **Google Patents:** https://patents.google.com/patent/${encodeURIComponent(p.pub)}/en`,
    );
    lines.push('');
    lines.push('### Claim Chart');
    lines.push('');
    lines.push('| Claim | Type | Status | Confidence | Verbatim Quote (Verified) | Analysis |');
    lines.push('| --- | --- | --- | --- | --- | --- |');
    for (const row of p.rows || []) {
      const claim = p.claims.find((c) => c.num === row.num);
      const kind = claim?.dependent
        ? `Dep.${claim.depends_on?.length ? ` (#${claim.depends_on.join(',')})` : ''}`
        : 'Indep.';
      const quoteCell = row.quote
        ? `"${row.quote.replace(/\|/g, '\\|')}"${row.quote_span ? ` \`[${row.quote_span[0]}..${row.quote_span[1]}]\`` : ''}`
        : row.quote_rejected
          ? `REJECTED (${row.rejection_diagnostic?.label ?? 'unverified'})`
          : '—';
      const note = row.explanation.replace(/\|/g, '\\|');
      lines.push(
        `| ${row.num} | ${kind} | ${row.status} | ${Math.round(row.confidence * 100)}% | ${quoteCell} | ${note} |`,
      );
    }
    lines.push('');
  }

  lines.push('---');
  lines.push('*Research aid generated by Verbatim. Not legal advice.*');
  return lines.join('\n');
}

export function downloadMarkdownReport(result: SearchRunResult, selectedPatent?: AnalyzedPatent): void {
  const md = buildMarkdownReport(result, selectedPatent);
  const slug = selectedPatent ? selectedPatent.pub : 'top5-claim-chart';
  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `verbatim-${slug}.md`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
